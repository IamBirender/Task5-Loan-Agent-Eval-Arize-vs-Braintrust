def case(
    name, description, agent, user, expected, gate, method, tools=None,
    guidelines=None, forbidden=None, patterns=None, fault=None, limits=None, turns=None,
):
    inputs = {"SessionId": f"sess-{name.lower()}"}
    if turns:
        inputs["Turns"] = turns
    else:
        inputs["UserInput"] = user
    rec = {
        "name": name,
        "description": description,
        "evaluatedAgent": agent,
        "inputs": inputs,
        "expectations": {
            "expectedResponse": {"Response": expected},
            "guidelines": guidelines or [],
            "expectedTools": [{"name": t, "arguments": {}} for t in (tools or [])],
        },
        "metadata": {
            "testId": name,
            "qualityGate": gate,
            "phase": "Pre-PR · Validate",
            "evaluationMethod": method,
            "source": "added by us",
        },
    }
    if forbidden:
        rec["expectations"]["forbiddenValues"] = forbidden
    if patterns:
        rec["expectations"]["forbiddenPatterns"] = patterns
    if fault:
        rec["metadata"]["fault"] = fault
    if limits:
        rec["metadata"]["limits"] = limits
        rec["metadata"]["phase"] = "Release ready"
    return rec


